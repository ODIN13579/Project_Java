-- SwiftletCare PostgreSQL schema | ERD DSN-07 | 17 tables
-- PostgreSQL 14+ | Database: swiftletcare | Schema: public
-- One-time installation. DO NOT rerun once the schema has been installed.
-- Flyway copy: backend/src/main/resources/db/migration/V1__create_swiftletcare_schema.sql
-- Timestamps use TIMESTAMPTZ. Spring Boot should map them to Instant.
-- IMPORTANT: quoted column names "on", "timestamp", "date" match the ERD.

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(150),
    phone VARCHAR(30),
    role VARCHAR(30) NOT NULL DEFAULT 'OWNER',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_users_email_not_blank CHECK (btrim(email) <> ''),
    CONSTRAINT ck_users_role CHECK (role IN ('OWNER', 'ADMIN'))
);

CREATE TABLE houses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    address TEXT,
    description TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_houses_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE house_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    house_id BIGINT NOT NULL REFERENCES houses(id) ON DELETE RESTRICT,
    role VARCHAR(30) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_memberships_user_house UNIQUE (user_id, house_id),
    CONSTRAINT ck_memberships_role CHECK (role IN ('OWNER', 'ADMIN', 'VIEWER'))
);

CREATE TABLE zones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    house_id BIGINT NOT NULL REFERENCES houses(id) ON DELETE RESTRICT,
    name VARCHAR(150) NOT NULL,
    floor_label VARCHAR(50),
    area_m2 DOUBLE PRECISION,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_zones_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_zones_area CHECK (area_m2 IS NULL OR area_m2 > 0)
);

CREATE TABLE devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id BIGINT NOT NULL REFERENCES zones(id) ON DELETE RESTRICT,
    device_id VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    type VARCHAR(20) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    online BOOLEAN NOT NULL DEFAULT FALSE,
    last_seen_at TIMESTAMPTZ,
    CONSTRAINT ck_devices_identifier CHECK (btrim(device_id) <> ''),
    CONSTRAINT ck_devices_name CHECK (btrim(name) <> ''),
    CONSTRAINT ck_devices_type CHECK (type IN ('ESP32', 'CAMERA'))
);

CREATE TABLE zone_configs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id BIGINT NOT NULL REFERENCES zones(id) ON DELETE RESTRICT,
    humidity_on DOUBLE PRECISION,
    humidity_off DOUBLE PRECISION,
    temp_min DOUBLE PRECISION,
    temp_max DOUBLE PRECISION,
    temp_hysteresis DOUBLE PRECISION,
    co2_min DOUBLE PRECISION,
    co2_max DOUBLE PRECISION,
    light_min DOUBLE PRECISION,
    light_max DOUBLE PRECISION,
    telemetry_interval_sec INTEGER NOT NULL DEFAULT 5,
    heartbeat_interval_sec INTEGER NOT NULL DEFAULT 2,
    version INTEGER NOT NULL DEFAULT 1,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_zone_configs_zone UNIQUE (zone_id),
    CONSTRAINT ck_zone_configs_humidity_on CHECK (humidity_on IS NULL OR humidity_on BETWEEN 0 AND 100),
    CONSTRAINT ck_zone_configs_humidity_off CHECK (humidity_off IS NULL OR humidity_off BETWEEN 0 AND 100),
    CONSTRAINT ck_zone_configs_hysteresis_humidity CHECK (humidity_on IS NULL OR humidity_off IS NULL OR humidity_on < humidity_off),
    CONSTRAINT ck_zone_configs_temperature CHECK (temp_min IS NULL OR temp_max IS NULL OR temp_min < temp_max),
    CONSTRAINT ck_zone_configs_temp_hysteresis CHECK (temp_hysteresis IS NULL OR temp_hysteresis > 0),
    CONSTRAINT ck_zone_configs_co2 CHECK (
        (co2_min IS NULL OR co2_min >= 0) AND
        (co2_max IS NULL OR co2_max >= 0) AND
        (co2_min IS NULL OR co2_max IS NULL OR co2_min <= co2_max)
    ),
    CONSTRAINT ck_zone_configs_light CHECK (
        (light_min IS NULL OR light_min >= 0) AND
        (light_max IS NULL OR light_max >= 0) AND
        (light_min IS NULL OR light_max IS NULL OR light_min <= light_max)
    ),
    CONSTRAINT ck_zone_configs_telemetry_interval CHECK (telemetry_interval_sec BETWEEN 1 AND 60),
    CONSTRAINT ck_zone_configs_heartbeat_interval CHECK (heartbeat_interval_sec BETWEEN 1 AND 60),
    CONSTRAINT ck_zone_configs_version CHECK (version >= 1)
);

CREATE TABLE sensors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL REFERENCES devices(id) ON DELETE RESTRICT,
    kind VARCHAR(80) NOT NULL,
    unit VARCHAR(30),
    CONSTRAINT ck_sensors_kind_not_blank CHECK (btrim(kind) <> '')
);

CREATE TABLE actuators (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL REFERENCES devices(id) ON DELETE RESTRICT,
    kind VARCHAR(20) NOT NULL,
    mode VARCHAR(20) NOT NULL DEFAULT 'AUTO',
    "on" BOOLEAN NOT NULL DEFAULT FALSE,
    manual_until TIMESTAMPTZ,
    CONSTRAINT ck_actuators_kind CHECK (kind IN ('MIST','FAN','HEATER','AMPLIFIER')),
    CONSTRAINT ck_actuators_mode CHECK (mode IN ('AUTO','MANUAL'))
);

CREATE TABLE telemetry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL REFERENCES devices(id) ON DELETE RESTRICT,
    event_id VARCHAR(150) NOT NULL,
    "timestamp" TIMESTAMPTZ NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    temperature DOUBLE PRECISION,
    humidity DOUBLE PRECISION,
    co2 DOUBLE PRECISION,
    light DOUBLE PRECISION,
    sensor_status VARCHAR(30) NOT NULL,
    CONSTRAINT uq_telemetry_device_event UNIQUE (device_id, event_id),
    CONSTRAINT ck_telemetry_event_id_not_blank CHECK (btrim(event_id) <> ''),
    CONSTRAINT ck_telemetry_humidity CHECK (humidity IS NULL OR humidity BETWEEN 0 AND 100),
    CONSTRAINT ck_telemetry_co2 CHECK (co2 IS NULL OR co2 >= 0),
    CONSTRAINT ck_telemetry_light CHECK (light IS NULL OR light >= 0),
    CONSTRAINT ck_telemetry_sensor_status CHECK (sensor_status IN ('OK','PARTIAL_ERROR','ERROR'))
);

CREATE TABLE control_commands (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actuator_id BIGINT NOT NULL REFERENCES actuators(id) ON DELETE RESTRICT,
    requested_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    command_id VARCHAR(150) NOT NULL UNIQUE,
    action VARCHAR(20) NOT NULL,
    target_state BOOLEAN,
    target_mode VARCHAR(20),
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    sent_at TIMESTAMPTZ,
    ack_at TIMESTAMPTZ,
    failure_reason TEXT,
    expires_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_control_commands_action CHECK (action IN ('SET_MODE','SET_STATE')),
    CONSTRAINT ck_control_commands_target_mode CHECK (target_mode IS NULL OR target_mode IN ('AUTO','MANUAL')),
    CONSTRAINT ck_control_commands_status CHECK (status IN ('PENDING','SENT','ACKNOWLEDGED','FAILED','REJECTED','EXPIRED')),
    CONSTRAINT ck_control_commands_target_xor CHECK (
       (action = 'SET_MODE' AND target_mode IS NOT NULL AND target_state IS NULL)
       OR (action = 'SET_STATE' AND target_state IS NOT NULL AND target_mode IS NULL)
    ),
    CONSTRAINT ck_control_commands_expiry CHECK (expires_at > requested_at)
);

CREATE TABLE count_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL REFERENCES devices(id) ON DELETE RESTRICT,
    period_start TIMESTAMPTZ NOT NULL,
    period_end TIMESTAMPTZ NOT NULL,
    entry_count INTEGER NOT NULL,
    exit_count INTEGER NOT NULL,
    detect_count INTEGER NOT NULL,
    aggregation_type VARCHAR(20) NOT NULL,
    processed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_count_logs_period CHECK (period_start < period_end),
    CONSTRAINT ck_count_logs_counts CHECK (entry_count >= 0 AND exit_count >= 0 AND detect_count >= 0),
    CONSTRAINT ck_count_logs_aggregation CHECK (aggregation_type IN ('HOURLY','DAILY'))
);

CREATE TABLE anomaly_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL REFERENCES devices(id) ON DELETE RESTRICT,
    species VARCHAR(100),
    confidence DOUBLE PRECISION NOT NULL,
    detected_at TIMESTAMPTZ NOT NULL,
    snapshot_path TEXT,
    CONSTRAINT ck_anomaly_events_confidence CHECK (confidence BETWEEN 0 AND 1)
);

CREATE TABLE alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id BIGINT NOT NULL REFERENCES zones(id) ON DELETE RESTRICT,
    anomaly_event_id BIGINT REFERENCES anomaly_events(id) ON DELETE RESTRICT,
    type VARCHAR(80) NOT NULL,
    level VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'NEW',
    message TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    handled_at TIMESTAMPTZ,
    CONSTRAINT ck_alerts_type CHECK (btrim(type) <> ''),
    CONSTRAINT ck_alerts_level CHECK (level IN ('WARNING','CRITICAL')),
    CONSTRAINT ck_alerts_status CHECK (status IN ('NEW','IN_PROGRESS','RESOLVED'))
);

CREATE TABLE alert_histories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id BIGINT NOT NULL REFERENCES alerts(id) ON DELETE RESTRICT,
    changed_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    from_status VARCHAR(20),
    to_status VARCHAR(20) NOT NULL,
    change_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    note TEXT,
    CONSTRAINT ck_alert_histories_from_status CHECK (from_status IS NULL OR from_status IN ('NEW','IN_PROGRESS','RESOLVED')),
    CONSTRAINT ck_alert_histories_to_status CHECK (to_status IN ('NEW','IN_PROGRESS','RESOLVED'))
);

CREATE TABLE notification_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id BIGINT NOT NULL REFERENCES alerts(id) ON DELETE RESTRICT,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    channel VARCHAR(15) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    failure_reason TEXT,
    CONSTRAINT ck_notifications_channel CHECK (channel IN ('WEB','PUSH')),
    CONSTRAINT ck_notifications_status CHECK (status IN ('PENDING','SENT','DELIVERED','FAILED'))
);

CREATE TABLE reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    type VARCHAR(80) NOT NULL,
    range_from TIMESTAMPTZ NOT NULL,
    range_to TIMESTAMPTZ NOT NULL,
    file_path TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_reports_type_not_blank CHECK (btrim(type) <> ''),
    CONSTRAINT ck_reports_range CHECK (range_from < range_to)
);

CREATE TABLE harvest_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id BIGINT NOT NULL REFERENCES zones(id) ON DELETE RESTRICT,
    "date" DATE NOT NULL,
    yield_kg DOUBLE PRECISION NOT NULL,
    note TEXT,
    CONSTRAINT ck_harvest_logs_yield CHECK (yield_kg >= 0)
);

-- Time-series read paths used by dashboard/reporting.
CREATE INDEX idx_memberships_house_active ON house_memberships (house_id, active);
CREATE INDEX idx_zones_house ON zones (house_id);
CREATE INDEX idx_devices_zone ON devices (zone_id);
CREATE INDEX idx_devices_online_last_seen ON devices (online, last_seen_at);
CREATE INDEX idx_sensors_device ON sensors (device_id);
CREATE INDEX idx_actuators_device ON actuators (device_id);
CREATE INDEX idx_telemetry_device_time ON telemetry (device_id, "timestamp" DESC);
CREATE INDEX idx_telemetry_received_at ON telemetry (received_at DESC);
CREATE INDEX idx_commands_actuator_requested ON control_commands (actuator_id, requested_at DESC);
CREATE INDEX idx_commands_status_expiry ON control_commands (status, expires_at);
CREATE INDEX idx_count_logs_device_period ON count_logs (device_id, period_start DESC, period_end DESC);
CREATE INDEX idx_anomalies_device_detected ON anomaly_events (device_id, detected_at DESC);
CREATE INDEX idx_alerts_zone_created ON alerts (zone_id, created_at DESC);
CREATE INDEX idx_alerts_status_created ON alerts (status, created_at DESC);
CREATE INDEX idx_alerts_anomaly ON alerts (anomaly_event_id) WHERE anomaly_event_id IS NOT NULL;
CREATE INDEX idx_alert_histories_alert_time ON alert_histories (alert_id, change_at DESC);
CREATE INDEX idx_notifications_recipient_created ON notification_deliveries (user_id, created_at DESC);
CREATE INDEX idx_notifications_pending ON notification_deliveries (status, created_at) WHERE status IN ('PENDING','FAILED');
CREATE INDEX idx_reports_author_created ON reports (created_by, created_at DESC);
CREATE INDEX idx_harvest_zone_date ON harvest_logs (zone_id, "date" DESC);

COMMENT ON COLUMN devices.id IS 'Internal numeric primary key; distinct from MQTT devices.device_id string.';
COMMENT ON COLUMN devices.device_id IS 'External MQTT device identifier (e.g. ESP32-001).';
COMMENT ON COLUMN telemetry.event_id IS 'Immutable MQTT event_id. Deduplicated per device. Backend ACK STORED only after commit.';
COMMENT ON COLUMN telemetry.device_id IS 'BIGINT foreign key to devices.id, not MQTT string device_id.';
COMMENT ON COLUMN actuators."on" IS 'Last GPIO state reported by the device, not verified physical load feedback.';
COMMENT ON COLUMN count_logs.detect_count IS 'Detection metric meaning not finally ratified by AI team (OPEN).';
COMMENT ON TABLE anomaly_events IS 'AI source event idempotency key remains OPEN; no unapproved source_event_id added.';
COMMENT ON TABLE control_commands IS 'Application command ACK differs from MQTT PUBACK; expires_at always required.';
COMMENT ON TABLE alert_histories IS 'changed_by NULL means SYSTEM by v1 convention, not yet a separate actor_type.';
