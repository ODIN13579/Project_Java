CREATE TABLE swiftletcare.users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email VARCHAR(255) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, full_name VARCHAR(150), phone VARCHAR(30),
 role VARCHAR(30) NOT NULL CHECK(role IN ('OWNER','ADMIN')), active BOOLEAN NOT NULL);
CREATE TABLE swiftletcare.houses (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(150) NOT NULL,
 address TEXT, description TEXT, active BOOLEAN NOT NULL);
CREATE TABLE swiftletcare.house_memberships (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES swiftletcare.users,
 house_id BIGINT NOT NULL REFERENCES swiftletcare.houses, role VARCHAR(30) NOT NULL CHECK(role IN ('OWNER','ADMIN','VIEWER')),
 active BOOLEAN NOT NULL, joined_at TIMESTAMPTZ NOT NULL, UNIQUE(user_id,house_id));
CREATE TABLE swiftletcare.zones (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, house_id BIGINT NOT NULL REFERENCES swiftletcare.houses,
 name VARCHAR(150) NOT NULL, floor_label VARCHAR(50), area_m2 DOUBLE PRECISION CHECK(area_m2 >= 0), active BOOLEAN NOT NULL);
CREATE TABLE swiftletcare.devices (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, zone_id BIGINT NOT NULL REFERENCES swiftletcare.zones,
 device_id VARCHAR(100) NOT NULL UNIQUE, name VARCHAR(150) NOT NULL,
 type VARCHAR(20) NOT NULL CHECK(type IN ('ESP32','CAMERA')), enabled BOOLEAN NOT NULL,
 online BOOLEAN NOT NULL DEFAULT FALSE, last_seen_at TIMESTAMPTZ);
CREATE TABLE swiftletcare.telemetry (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, device_id BIGINT NOT NULL REFERENCES swiftletcare.devices,
 event_id VARCHAR(150) NOT NULL, timestamp TIMESTAMPTZ NOT NULL, received_at TIMESTAMPTZ NOT NULL,
 temperature DOUBLE PRECISION, humidity DOUBLE PRECISION CHECK(humidity BETWEEN 0 AND 100),
 co2 DOUBLE PRECISION CHECK(co2 >= 0), light DOUBLE PRECISION CHECK(light >= 0),
 sensor_status VARCHAR(30) NOT NULL CHECK(sensor_status IN ('OK','PARTIAL_ERROR','ERROR')),
 UNIQUE(device_id,event_id));
CREATE INDEX telemetry_device_time ON swiftletcare.telemetry(device_id,timestamp DESC,received_at DESC,id DESC);
CREATE INDEX devices_online_seen ON swiftletcare.devices(last_seen_at) WHERE online;
CREATE TABLE swiftletcare.count_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, device_id BIGINT NOT NULL REFERENCES swiftletcare.devices,
 period_start TIMESTAMPTZ NOT NULL, period_end TIMESTAMPTZ NOT NULL,
 entry_count INTEGER NOT NULL CHECK(entry_count>=0), exit_count INTEGER NOT NULL CHECK(exit_count>=0),
 detect_count INTEGER NOT NULL CHECK(detect_count>=0), aggregation_type VARCHAR(20) NOT NULL CHECK(aggregation_type IN ('HOURLY','DAILY')),
 processed_at TIMESTAMPTZ NOT NULL, CHECK(period_start < period_end),
 UNIQUE(device_id,aggregation_type,period_start,period_end));
